interface Ctx { lang: Lang; dir: 'rtl' | 'ltr'; t: (k: string) => string; setLang: (l: Lang) => void; name: (o: { name_ar: string; name_en: string } | null | undefined) => string }
const I18nContext = createContext<Ctx>(null!)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => { try { return (localStorage.getItem('ms_lang') as Lang) || 'ar' } catch { return 'ar' } })
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])
  const value = useMemo<Ctx>(() => ({
    lang,
    dir: lang === 'ar' ? 'rtl' : 'ltr',
    setLang: (l) => { setLangState(l); try { localStorage.setItem('ms_lang', l) } catch { /* ignore */ } },
    t: (k) => (dict[k] ? dict[k][lang === 'ar' ? 0 : 1] : k),
    name: (o) => (o ? (lang === 'ar' ? o.name_ar : o.name_en) : ''),
  }), [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)

export function fmtMoney(v: number | null | undefined, digits = 2): string {
  if (v === null || v === undefined) return '—'
  return v.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })
}
export function fmtDate(s: string | null | undefined, lang: Lang = 'ar'): string {
  if (!s) return '—'
  const d = new Date(s.endsWith('Z') || s.includes('+') ? s : s + 'Z')
  return d.toLocaleDateString(lang === 'ar' ? 'ar-SA-u-nu-latn-ca-gregory' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric' })
}
